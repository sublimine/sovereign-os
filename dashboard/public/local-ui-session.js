// Local console session recovery.
//
// `uiToken` is deliberately an in-memory, per-console-process capability. A
// console restart invalidates it, which is the right security behaviour. This
// helper obtains a replacement only from the existing same-origin bootstrap
// endpoint. It never retries the operation which encountered the stale token:
// in particular, no POST/PUT/PATCH/DELETE can be replayed by session recovery.

export class LocalUiSessionError extends Error {
  constructor(message, {status = 0, code = 'CONSOLE_REQUEST'} = {}) {
    super(message);
    this.name = 'LocalUiSessionError';
    this.status = status;
    this.code = code;
  }
}

function object(value) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {};
}

async function responseJson(response) {
  try { return await response.json(); } catch { return {}; }
}

function errorFromPayload(response, payload, fallback) {
  const body = object(payload);
  return new LocalUiSessionError(
    typeof body.message === 'string' && body.message.trim() ? body.message : fallback,
    {status: Number(response?.status) || 0, code: typeof body.code === 'string' ? body.code : 'CONSOLE_REQUEST'},
  );
}

function assertBootstrap(payload) {
  const body = object(payload);
  // The UI token is generated by the console with randomBytes(32). The
  // browser need not know its format, but it must reject an absent or clearly
  // malformed bootstrap document rather than overwriting its current token.
  if (typeof body.token !== 'string' || body.token.length < 16) {
    throw new LocalUiSessionError('La consola no devolvió una nueva sesión local válida.', {code: 'INVALID_BOOTSTRAP_SESSION'});
  }
  return body;
}

/**
 * Makes stale local UI sessions recoverable without weakening the server's
 * same-origin/token gate. Call `errorForResponse` only after a response has
 * failed. It consumes an error body, renews the in-memory token at most once
 * for concurrent failures, and returns a new error explaining that the
 * original operation was not replayed.
 */
export function createLocalUiSessionRecovery({fetchImpl = globalThis.fetch, applyBootstrap} = {}) {
  if (typeof fetchImpl !== 'function') throw new TypeError('fetchImpl debe ser una función.');
  if (typeof applyBootstrap !== 'function') throw new TypeError('applyBootstrap debe ser una función.');

  let recoveryInFlight = null;

  async function renew() {
    if (recoveryInFlight) return recoveryInFlight;
    const pending = (async () => {
      let response;
      try {
        response = await fetchImpl('/api/bootstrap', {
          method: 'GET',
          headers: {'accept': 'application/json'},
          credentials: 'same-origin',
          cache: 'no-store',
        });
      } catch {
        throw new LocalUiSessionError('No se pudo volver a conectar con la consola local. Espera a que termine de reiniciarse y actualiza la página.', {code: 'LOCAL_UI_SESSION_RENEWAL_FAILED'});
      }
      const payload = await responseJson(response);
      if (!response.ok) {
        throw errorFromPayload(response, payload, 'La consola no pudo renovar la sesión local.');
      }
      const bootstrap = assertBootstrap(payload);
      // The application receives only the bounded bootstrap document already
      // served to an initial page load. No former action body is retained or
      // sent alongside this read.
      await applyBootstrap(bootstrap);
      return bootstrap;
    })();
    recoveryInFlight = pending;
    try {
      return await pending;
    } finally {
      if (recoveryInFlight === pending) recoveryInFlight = null;
    }
  }

  async function errorForResponse(response, fallback) {
    const payload = await responseJson(response);
    const failure = errorFromPayload(response, payload, fallback);
    if (failure.code !== 'INVALID_UI_SESSION') return failure;
    try {
      await renew();
    } catch {
      return new LocalUiSessionError(
        'La sesión local ya no es válida y la consola no pudo renovarla. Actualiza la página cuando el servicio local esté disponible.',
        {status: failure.status || 403, code: 'LOCAL_UI_SESSION_RENEWAL_FAILED'},
      );
    }
    return new LocalUiSessionError(
      'La consola se reinició y renovó la sesión local. La operación anterior no se ha repetido; vuelve a iniciarla.',
      {status: failure.status || 403, code: 'LOCAL_UI_SESSION_RENEWED'},
    );
  }

  return {renew, errorForResponse};
}
